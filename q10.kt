//Function to check whether a character is vowel or consonant
fun main() {
    val ch = 'a'
    if (ch == 'a' || ch == 'e' || ch == 'i' || ch == 'o' || ch == 'u' ||
        ch == 'A' || ch == 'E' || ch == 'I' || ch == 'O' || ch == 'U') {
        println("$ch is a Vowel")
    } 
    else {
        println("$ch is a Consonant")
    }
}
